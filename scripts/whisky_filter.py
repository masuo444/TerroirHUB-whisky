#!/usr/bin/env python3
"""
楽天商品が「ウイスキー（ジャパニーズウイスキー等）」かどうかを判定する共通フィルタ。
wine/sake と同設計だがウイスキー語彙。蒸留所名キーワード検索で混入する
非ウイスキー（服飾・グラス・書籍・他カテゴリ酒類・木綿等の同名品）を除外する。
方針: 精度優先（ウイスキー以外を出さない）。
"""
import re

# 非飲料（服飾・雑貨・グラス・書籍・食品）。ウイスキー語があっても除外
_EXCLUDE_HARD = re.compile(
    r'カーディガン|スカート|ニット|セーター|シャツ|Tシャツ|ブラウス|ワンピース|パンツ|デニム|ジーンズ'
    r'|コート|ジャケット|アウター|パーカー|スウェット|スカジャン|半纏|法被|前掛け|エプロン|木綿|手ぬぐい'
    r'|ランジェリー|インナー|下着|靴下|帽子|マフラー|手袋|スニーカー|シューズ'
    r'|バッグ|\bbag\b|カバン|鞄|財布|ポーチ|リュック|ピアス|ネックレス|ブレスレット|指輪|アクセサリ'
    r'|腕時計|掛け時計|サングラス|眼鏡|スマホケース|手芸|フィギュア|ぬいぐるみ|ボールペン|タオル|マット|クッション'
    # グラス・食器類（ロックグラス/ウイスキーグラス等）
    r'|ワイングラス|ロックグラス|ウイスキーグラス|グラスセット|タンブラー|食器|お皿|プレート|ボウル|カトラリー|急須|湯呑|栓抜き|アイスペール|アイストング'
    # 書籍
    r'|電子書籍|\bebook\b|kindle|楽天kobo|文庫|新書|コミック|単行本|写真集|カレンダー'
    # 食品・その他（化粧箱/ギフト箱は除外しない）
    r'|チョコレート|チョコ|ケーキ|クッキー|焼き菓子|ジャム|ドレッシング|レトルト|ソーセージ|燻製|スモークサーモン|石鹸|化粧水|コスメ',
    re.IGNORECASE,
)

# ウイスキーであるシグナル（いずれか1つ以上）
_WHISKY = re.compile(
    r'ウイスキー|ウィスキー|whisky|whiskey|ジャパニーズウイスキー'
    r'|シングルモルト|シングルグレーン|ブレンデッド|ピュアモルト|ヴァッテッド|モルト原酒'
    r'|バーボン|スコッチ|アイリッシュ|テネシー|ライウイスキー'
    r'|ニューポット|ニューメイク|ニューボーン|原酒|樽熟成|カスク|\bcask\b|ピーテッド|ノンピート|ミズナラ'
    r'|蒸溜所|蒸留所|distillery|ディスティラリー',
    re.IGNORECASE,
)

# 年数表記（12年など）・ウイスキーの定番容量は補助シグナル
_AGE = re.compile(r'\d{1,2}\s*年|\bage\b|\d{1,2}yo\b|エイジド', re.IGNORECASE)
_VOL = re.compile(r'(700|750|350|200|180|500|50)\s?ml', re.IGNORECASE)

# 他カテゴリの酒類（ウイスキー語が無い場合のみ除外）
_EXCLUDE_BOOZE = re.compile(
    r'日本酒|清酒|純米|吟醸|本醸造|大吟醸'
    r'|ワイン|\bwine\b|ヴァン|スパークリング|シャンパン'
    r'|焼酎|泡盛|麦焼酎|芋焼酎|米焼酎'
    r'|ビール|発泡酒|\bbeer\b|クラフトビール|エール|ラガー'
    r'|梅酒|果実酒|リキュール|サワー|チューハイ|甘酒|どぶろく',
    re.IGNORECASE,
)


def is_whisky_item(name: str) -> bool:
    """商品名がウイスキーとして妥当ならTrue。"""
    if not name:
        return False
    if _EXCLUDE_HARD.search(name):       # 非飲料
        return False
    if _WHISKY.search(name):             # ウイスキーシグナル → 採用
        return True
    if _EXCLUDE_BOOZE.search(name):      # 他カテゴリ酒類 → 除外
        return False
    if _AGE.search(name) or _VOL.search(name):  # 年数表記/定番容量があり除外語も無い → ウイスキーとみなす
        return True
    return False


if __name__ == '__main__':
    tests = [
        ('サントリー 知多 700ml グレーンウイスキー', True),
        ('サントリーシングルモルトウイスキー 山崎12年 箱付', True),
        ('厚岸 ニューボーン Foundations 200ml', True),
        ('秩父 イチローズモルト ダブルディスティラリーズ 700ml', True),
        ('知多木綿 手ぬぐい 和柄', False),
        ('八海山 純米大吟醸 1800ml', False),
        ('グレイスワイン 甲州 750ml', False),
        ('ロックグラス 2個セット 名入れ ウイスキー', False),
        ('金しゃちビール ピルスナー', False),
        ('響 ジャパニーズハーモニー 700ml 化粧箱', True),
    ]
    ok = 0
    for nm, exp in tests:
        got = is_whisky_item(nm)
        m = 'OK' if got == exp else 'NG'
        if got == exp:
            ok += 1
        print(f'  [{m}] {got!s:5} (期待{exp!s:5}) {nm}')
    print(f'\n{ok}/{len(tests)} passed')
